export const getScrewProducts = () => {
  const results = []
  const products = Object.values(SCREW_PRODUCTS)

  for (let i = 0; i < products.length; i++) {
    const product = products[i]

    for (let pi = 0; pi < product.items.length; pi++) {
      const piItem = product.items[pi]

      if (piItem.quantity) {
        results.push({
          name: piItem.name.trim(),
          type: 'SCREW',
          properties: {
            [piItem.propertyId]: piItem.propertyDetailId
          },
          date: '20240219',
          branch: product.branchId,
          quantity: piItem.quantity
        })
      }
    }
  }

  return results
}
